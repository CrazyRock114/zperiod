/* ── engine ───────────────────────────────────────────────────────────── */

const problems = [];

function readJSON(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** Keys in the file that this slice does NOT own — must survive untouched. */
function foreignKeys(data) {
  return Object.keys(data).filter((k) => !MY_KEYS.includes(k));
}

function mergeLocale(code) {
  const file = join(T, `${code}.json`);
  if (!existsSync(file)) {
    problems.push(`${code}: no dictionary file`);
    return null;
  }
  const before = readJSON(file);
  const pack = DICT[code];
  if (!pack) {
    problems.push(`${code}: no translation pack`);
    return null;
  }

  // every slot of every lesson must be present and non-blank
  for (const k of MY_KEYS) {
    const v = pack[k];
    if (typeof v !== 'string' || !v.trim()) {
      problems.push(`${code}: pack key ${k} missing or empty`);
      return null;
    }
  }
  for (const k of Object.keys(pack)) {
    if (!MY_KEYS.includes(k)) problems.push(`${code}: stray pack key ${k}`);
  }

  const data = { ...before };
  for (const k of MY_KEYS) data[k] = pack[k]; // existing keys keep their slot

  // --- non-destruction assertions -------------------------------------
  const kept = foreignKeys(data);
  const beforeKeys = foreignKeys(before);
  if (kept.length !== beforeKeys.length) {
    problems.push(`${code}: foreign key count ${beforeKeys.length} -> ${kept.length}`);
    return null;
  }
  for (const k of beforeKeys) {
    if (data[k] !== before[k]) problems.push(`${code}: foreign key ${k} mutated`);
    if (!(k in data)) problems.push(`${code}: foreign key ${k} dropped`);
  }
  if (Object.keys(before).some((k) => !(k in data))) {
    problems.push(`${code}: a pre-existing key disappeared`);
  }
  for (const k of MY_KEYS) {
    if (!(k in data) || typeof data[k] !== 'string' || !data[k].trim()) {
      problems.push(`${code}: slice key ${k} not written`);
    }
  }
  if (problems.length) return null;

  writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
  return { kept: beforeKeys.length, total: Object.keys(data).length };
}

/** Re-merge until stable — survives a concurrent writer touching the file. */
function run(passes = 4) {
  for (let p = 0; p < passes; p++) {
    problems.length = 0;
    let wrote = 0;
    for (const code of LOCALES) if (mergeLocale(code)) wrote++;
    if (!problems.length) {
      if (p > 0) console.log(`stabilised after ${p + 1} pass(es)`);
      return true;
    }
    console.error(`pass ${p + 1}: ${problems.length} problem(s) — retrying`);
    for (const msg of problems.slice(0, 10)) console.error(`  ${msg}`);
  }
  return false;
}

/** Independent read-back verification of the files on disk. */
function check() {
  const en = readJSON(join(T, 'en.json'));
  const errs = [];
  let identicalToEn = 0;
  for (const code of LOCALES) {
    const d = readJSON(join(T, `${code}.json`));
    for (const k of MY_KEYS) {
      if (!(k in d)) errs.push(`${code} missing ${k}`);
      else if (typeof d[k] !== 'string' || !d[k].trim()) errs.push(`${code} empty ${k}`);
      else if (code !== 'en' && d[k] === en[k]) identicalToEn++;
    }
    for (const k of ['nav.table', 'settings.title', 'tools.balancer.title']) {
      if (!(k in d)) errs.push(`${code} lost pre-existing ${k}`);
    }
    if (Object.keys(d).length < 440) errs.push(`${code} only ${Object.keys(d).length} keys`);
  }
  if (identicalToEn > 8) errs.push(`${identicalToEn} values identical to English`);
  if (errs.length) {
    console.error(`FAIL (${errs.length})`);
    for (const e of errs.slice(0, 30)) console.error(e);
    process.exitCode = 1;
  } else {
    console.log(`OK ${MY_KEYS.length} lesson keys x ${LOCALES.length} locales (${identicalToEn} value(s) identical to en)`);
  }
}

if (process.argv[1] && process.argv[1].endsWith('gen-lessons-d.mjs')) {
  if (process.argv.includes('--check')) check();
  else if (!run()) process.exitCode = 1;
}
