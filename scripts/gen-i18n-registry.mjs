#!/usr/bin/env node
/**
 * Scans the translations / element-name directories and rewrites
 * src/i18n/registry.ts so Vite can code-split every locale.
 *
 *   node scripts/gen-i18n-registry.mjs
 */
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const i18nDir = join(root, 'src/i18n');
const transDir = join(i18nDir, 'translations');
const namesDir = join(root, 'src/data/elementNames');

const list = (dir) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith('.json') && f !== 'index.json')
        .map((f) => f.replace(/\.json$/, ''))
        .sort()
    : [];

const ui = list(transDir);
const names = list(namesDir);

const entries = (codes) =>
  codes.length === 0
    ? '  // (none yet)'
    : codes.map((c) => `  ${JSON.stringify(c)}: () => import('./translations/${c}.json'),`).join('\n');

const nameEntries = (codes) =>
  codes.length === 0
    ? '  // (none yet)'
    : codes
        .map((c) => `  ${JSON.stringify(c)}: () => import('../data/elementNames/${c}.json'),`)
        .join('\n');

const arr = (codes) => (codes.length ? codes.map((c) => JSON.stringify(c)).join(', ') : '');

const out = `/**
 * Generated by \`node scripts/gen-i18n-registry.mjs\`.
 *
 * Static import map for the per-locale dictionaries and per-locale element
 * names. Vite can only code-split dynamic imports with a *statically
 * analysable* specifier, so the list of locales has to be baked in here
 * rather than built at runtime from a template literal.
 *
 * DO NOT EDIT BY HAND — rerun the generator after adding a locale.
 */

/** UI dictionaries, keyed by locale code. */
export const UI_DICTIONARIES: Record<string, () => Promise<{ default: Record<string, string> }>> = {
${entries(ui)}
};

/** Element-name tables, keyed by locale code. */
export const ELEMENT_NAMES: Record<string, () => Promise<{ default: Record<string, string> }>> = {
${nameEntries(names)}
};

/** Locales that actually shipped a UI dictionary. */
export const UI_LOCALES: string[] = [${arr(ui)}];

/** Locales that actually shipped element names. */
export const NAME_LOCALES: string[] = [${arr(names)}];
`;

writeFileSync(join(i18nDir, 'registry.ts'), out);
console.log(`registry: ${ui.length} UI dictionaries, ${names.length} element-name tables`);
if (!ui.length) console.warn('  ⚠ no translation files found yet');
